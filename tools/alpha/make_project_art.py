"""Generate original geometric project artwork; no input images or game assets."""
from pathlib import Path
import hashlib
import json
import struct
import zlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
A = ROOT / 'tools/alpha'
GENERATED = []

def font(size):
    for name in ('C:/Windows/Fonts/segoeuib.ttf', 'DejaVuSans.ttf'):
        try: return ImageFont.truetype(name, size)
        except OSError: pass
    return ImageFont.load_default()

def mark(size=512):
    im = Image.new('RGBA', (size, size))
    d = ImageDraw.Draw(im)
    d.ellipse((size*.08, size*.08, size*.92, size*.92), fill='#0d2541', outline='#72d7ea', width=max(1, size//24))
    points = [(x*size, y*size) for x,y in ((.25,.54),(.37,.54),(.44,.35),(.55,.68),(.63,.46),(.75,.46))]
    d.line(points, fill='#f1fafc', width=max(1,size//24), joint='curve')
    return im

def save(im, rel, **kwargs):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    im.save(path, **kwargs)
    GENERATED.append(rel)

def background(w, h):
    im = Image.new('RGB', (w,h), '#071322')
    d = ImageDraw.Draw(im)
    for y in range(h):
        k=y/max(1,h-1)
        d.line((0,y,w,y), fill=(7+int(5*k),19+int(10*k),34+int(14*k)))
    s=w/1100
    icon=mark(round(160*s))
    im.paste(icon,(round(w/2-icon.width/2),round(140*s)),icon)
    d.text((w/2,350*s),'OCARINA REBORN',font=font(round(44*s)),fill='#eef8ff',anchor='mm')
    d.text((w/2,402*s),'COMMUNITY SOFTWARE',font=font(round(17*s)),fill='#8cb5ca',anchor='mm')
    return im

def main():
    icon=mark()
    for n in (16,24,32,48,64,128,256):
        save(icon.resize((n,n),Image.Resampling.LANCZOS),f'tools/alpha/icon/icon-{n}.png')
    for n in (24,32,40,48,56,64,72,80,96,112):
        save(icon.resize((n,n),Image.Resampling.LANCZOS),f'tools/alpha/launcher/assets/ocarina-{n}.png')
    for rel in ('tools/alpha/icon/source.png','tools/alpha/icon/ocarina-source.png','tools/alpha/ocarina-icon.png',
                'tools/alpha/launcher/assets/icon44.png','engine/builder/HookshotBuilder/Images/ocarina_reborn.png',
                'engine/builder/py/hookshot_builder/assets/ocarina_reborn.png'):
        save(icon,rel)
    for rel in ('OcarinaReborn.ico','tools/alpha/OcarinaReborn.ico','engine/builder/py/hookshot_builder/assets/ocarina_reborn.ico',
                'engine/builder/setup/ocarina_reborn.ico'):
        save(icon,rel,format='ICO',sizes=[(n,n) for n in (16,24,32,48,64,128,256)])
    logo=Image.new('RGBA',(912,320))
    small=mark(150);logo.paste(small,(381,8),small)
    d=ImageDraw.Draw(logo)
    d.text((456,230),'OCARINA REBORN',font=font(64),fill='#eef8ff',anchor='mm')
    for rel in ('tools/alpha/startup-logo.png','engine/assets/ocarina_reborn.png'):
        save(logo,rel)
    for pct in (100,125,150,175,200):
        name='build-bg' if pct==100 else f'build-bg-{pct}'
        save(background(1100*pct//100,720*pct//100),f'tools/alpha/launcher/assets/{name}.png')
    save(background(1100,720),'tools/alpha/launcher/assets/keyart.png')
    raw=background(2200,1440)
    rel='tools/alpha/launcher/assets/build-bg.raw'
    (ROOT/rel).write_bytes(b'BGRAW1'+struct.pack('<HH',raw.width,raw.height)+zlib.compress(raw.tobytes(),9))
    GENERATED.append(rel)
    manifest={'origin':'Original circles, lines and project-name typography generated by tools/alpha/make_project_art.py. '
              'No game imagery, symbols, characters, voices or music. Local system font used for rendering; font binaries not redistributed.',
              'files':{rel:hashlib.sha256((ROOT/rel).read_bytes()).hexdigest() for rel in sorted(GENERATED)}}
    (A/'MEDIA-PROVENANCE.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print('Generated',len(GENERATED),'original artwork files.')

if __name__=='__main__':main()
